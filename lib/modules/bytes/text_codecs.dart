import 'dart:convert';

class TextCodecs {
  static const List<String> supported = [
    'utf-8',
    'latin1',
    'ascii',
    'windows-1251',
    'koi8-r',
    'koi8-u',
  ];

  static String? canonicalName(String name) {
    final String normalized = name.trim().toLowerCase().replaceAll('_', '-');
    switch (normalized) {
      case 'utf-8':
      case 'utf8':
        return 'utf-8';
      case 'latin1':
      case 'latin-1':
      case 'iso-8859-1':
      case 'iso8859-1':
      case 'l1':
        return 'latin1';
      case 'ascii':
      case 'us-ascii':
        return 'ascii';
      case 'windows-1251':
      case 'cp1251':
      case 'win-1251':
      case 'x-cp1251':
        return 'windows-1251';
      case 'koi8-r':
      case 'koi8r':
        return 'koi8-r';
      case 'koi8-u':
      case 'koi8u':
        return 'koi8-u';
    }
    return null;
  }

  static String decode(List<int> bytes, String encoding) {
    final String canonical = _require(encoding);
    switch (canonical) {
      case 'utf-8':
        return utf8.decode(bytes, allowMalformed: true);
      case 'latin1':
      case 'ascii':
        return latin1.decode(bytes.map((byte) => byte & 0xFF).toList());
    }
    final List<int> highHalf = _highHalf(canonical);
    final List<int> codeUnits = List<int>.filled(bytes.length, 0);
    for (int index = 0; index < bytes.length; index++) {
      final int byte = bytes[index] & 0xFF;
      codeUnits[index] = byte < 0x80 ? byte : highHalf[byte - 0x80];
    }
    return String.fromCharCodes(codeUnits);
  }

  static List<int> encode(String text, String encoding) {
    final String canonical = _require(encoding);
    switch (canonical) {
      case 'utf-8':
        return utf8.encode(text);
      case 'latin1':
      case 'ascii':
        return text.codeUnits
            .map((unit) => unit <= 0xFF ? unit : 0x3F)
            .toList();
    }
    final List<int> highHalf = _highHalf(canonical);
    final Map<int, int> reverse = {
      for (int index = 0; index < highHalf.length; index++)
        highHalf[index]: index + 0x80,
    };
    return text.runes
        .map((rune) => rune < 0x80 ? rune : (reverse[rune] ?? 0x3F))
        .toList();
  }

  static String _require(String encoding) {
    final String? canonical = canonicalName(encoding);
    if (canonical == null) {
      throw Exception(
          'unsupported encoding "$encoding", expected one of ${supported.join(', ')}');
    }
    return canonical;
  }

  static List<int> _highHalf(String canonical) {
    switch (canonical) {
      case 'windows-1251':
        return _windows1251HighHalf;
      case 'koi8-r':
        return _koi8rHighHalf;
      default:
        return _koi8uHighHalf;
    }
  }
}

